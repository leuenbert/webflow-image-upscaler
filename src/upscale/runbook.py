"""Generate UPLOAD_RUNBOOK.md, the instructions Claude in Chrome follows to upload the images."""
from __future__ import annotations

from collections import Counter

from .common import atomic_write_text
from .config import Config


def write_runbook(cfg: Config, rows: list[dict]) -> None:
    root = cfg.root
    py = root / ".venv" / "bin" / "python"
    n_items = len({r["item_slug"] for r in rows})
    c = Counter(r["upload_status"] for r in rows)
    collection = rows[0]["collection_id"] if rows else "?"
    max_mb = int(cfg.out["max_bytes"]) / 1e6
    flagged = [r for r in rows if r["quality_flag"]]

    text = f"""# Upload runbook — Webflow CMS "Projects" images

_Generated by `python -m upscale run`. Regenerate rather than edit by hand._

You are Claude in Chrome. Your job is to replace every image in the Webflow CMS collection
**Projects** (collection ID `{collection}`) with the upscaled file listed in the index. Upload through
the CMS editor's image fields only, because that is the only path where Webflow generates responsive
`srcset` versions. Do **not** use the Webflow API, CSV import or the Assets panel.

- Project folder: `{root}`
- Upload index: `{cfg.index_json}` (grouped by item → field → files) and `{cfg.index_csv}` (one row per slot)
- {len(rows)} slots in {n_items} items. Current status: {", ".join(f"{k}={v}" for k, v in sorted(c.items()))}
- Every upload file is a **WebP** (`.webp`), {cfg.target_width} px wide, ≤ {max_mb:.1f} MB.
- Upload **only** the `.webp` file named in `local_path`. Never upload anything from `cache/`
  (the `.jpg` files there are reference masters and are not meant for Webflow).

## 1. Before starting

1. Confirm the user has connected the folder `{root}` to this chat, so `file_upload` can read the files
   by their absolute `local_path`.
2. Confirm the Webflow Designer/CMS is open in Chrome on the **Projects** collection.
3. Open the collection settings and check every image field (`Main Image`, `Secondary Image`, `Gallery`,
   `Work — image #1`, `#2`, `#3`). None may have a max width/height below {cfg.target_width} px or a max
   file size below {max_mb:.1f} MB. If one does, stop and ask the user; do not change field settings yourself.
4. Check that the image fields accept WebP files. If an upload is rejected because of the file type,
   stop and ask the user.
5. Do not upload any slot whose `upload_status` is `not_ready`. If any exist, the pipeline has not
   finished; tell the user.

## 2. Order and resuming

- Work **one item at a time** in `index.json` order (`items[]`).
- Resume from the first item whose `item_status` is not `done` (any slot still `pending` or `failed`).
- Never touch slots already marked `uploaded`, `verified` or `skipped`.

## 3. For each item

1. Open the item in the CMS list by `item_name` (search box) and confirm the slug matches `item_slug`.
   Draft items (`is_draft: true`) stay drafts; do not change the draft/archive toggles.
2. **Single-image fields** (`field_type: single`):
   - Check that the current thumbnail is the image from `source_url` (same filename in its URL).
     If it is not, mark the slot `failed` with a note and move on.
   - Note the current **alt text** of the image. The CSV export does not contain it.
   - Use `find` / `read_page` to locate that field's `<input type="file">` and call `file_upload` with the
     slot's `local_path` — exactly one file per call. **Never click the file input** (a native file dialog
     would block the browser).
   - Wait until the new thumbnail shows. Check that the new image's URL ends in `.webp` and contains
     the slot's filename (e.g. `…--main.webp`); otherwise mark the slot `failed`. If the alt text was
     cleared, type it back in.
3. **Gallery** (`field_type: multi`):
   - Note the alt texts of the existing gallery images, in order.
   - Remove all existing gallery images.
   - Upload the new `.webp` files in `position` order, one `file_upload` call per file.
   - Check that the gallery now holds exactly `count_in_field` images in the right order. Restore alt
     texts by position.
4. **Save** the item (keep draft/staged status). **Do not publish** — the user publishes at the end.
5. Record progress for every slot (see §4). On an error, retry the slot once; if it fails again, mark it
   `failed` with a short note and continue with the next slot/item.

## 4. Recording progress

Preferred, if you can run a terminal command:

```
cd "{root}"
"{py}" -m upscale mark "<slot_id>" uploaded
"{py}" -m upscale mark "<item_slug>:gallery:*" uploaded          # glob for a whole gallery
"{py}" -m upscale mark "<slot_id>" failed --note "thumbnail did not match source_url"
"{py}" -m upscale status
```

Otherwise edit `index.csv` directly: set `upload_status` (`uploaded` / `verified` / `failed` / `skipped`),
`uploaded_at` (ISO timestamp) and `notes` for the slot's row. `mark` keeps `index.json` in sync; if you
edit the CSV by hand, `index.csv` is the source of truth.

Use `verified` after re-opening a saved item and confirming the new image is shown.

## 5. Reporting

- After every **5 items**, give the user a short progress report (items done / total, any failures).
- At the end, list:
  - every slot with `upload_status = failed` and its note,
  - every slot with `quality_flag` `low_source` or `size_over_budget` (the user may want to check these),
  - and remind the user that nothing has been published yet — they should review and **publish** the site.

## 6. Out of scope

Do not change any CMS field other than the image fields and their alt text. Do not publish. Do not use
the Webflow API, CSV import or Assets API.
"""
    if flagged:
        text += "\n## Appendix: slots with quality flags\n\n| slot_id | flag | source px |\n|---|---|---|\n"
        for r in flagged:
            text += f"| `{r['slot_id']}` | {r['quality_flag']} | {r['source_w']}×{r['source_h']} |\n"
    atomic_write_text(cfg.runbook, text)
